def norm(s):
    # 统一引号字符（文件使用 ASCII 直引号，脚本锚点可能含弯引号）
    return s.replace("“", '"').replace("”", '"').replace("‘", "'").replace("’", "'")

import re

def imgnames(suffix):
    return re.findall(r"images/([^\)]+)", suffix)

misses = []
for rel, anchor, suffix in EDITS:
    path = BASE + "/" + rel
    with io.open(path, "r", encoding="utf-8") as f:
        text = f.read()
    anchor_n = norm(anchor)
    if any(n in text for n in imgnames(suffix)):
        continue  # 该图片已插入，跳过（幂等）
    if anchor_n in text:
        text = text.replace(anchor_n, anchor_n + norm(suffix), 1)
        with io.open(path, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        misses.append((rel, anchor[:30]))

if misses:
    print("未命中 %d 处锚点：" % len(misses))
    for rel, a in misses:
        print("  %s :: %s…" % (rel, a))
else:
    print("全部 %d 处插入成功。" % len(EDITS))
